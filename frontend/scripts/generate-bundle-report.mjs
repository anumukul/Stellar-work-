#!/usr/bin/env node

/**
 * Generate a Markdown bundle size report suitable for posting as a PR comment.
 *
 * Reads:
 *   .next/analyze/bundle-size-report.json  (current build)
 *   .next/analyze/base-bundle-size-report.json  (base branch, optional)
 *
 * Outputs:
 *   .next/analyze/bundle-size-comment.md
 *
 * Usage:
 *   node scripts/generate-bundle-report.mjs
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const analyzeDir = path.join(root, ".next", "analyze");
const currentReportPath = path.join(analyzeDir, "bundle-size-report.json");
const baseReportPath = path.join(analyzeDir, "base-bundle-size-report.json");
const outputPath = path.join(analyzeDir, "bundle-size-comment.md");

// ── Load reports ─────────────────────────────────────────────────────────────

let current;
try {
  current = JSON.parse(await readFile(currentReportPath, "utf8"));
} catch {
  console.error("❌ Current bundle size report not found. Run check-bundle-size.mjs first.");
  process.exit(1);
}

let base = null;
try {
  base = JSON.parse(await readFile(baseReportPath, "utf8"));
} catch {
  // No base report — this is fine for first run or push-to-main
}

// ── Helpers ──────────────────────────────────────────────────────────────────

function delta(curr, prev) {
  if (prev == null) return "";
  const diff = curr - prev;
  if (diff === 0) return " (±0)";
  const sign = diff > 0 ? "+" : "";
  const pct = prev > 0 ? ` (${sign}${((diff / prev) * 100).toFixed(1)}%)` : "";
  return ` (${sign}${diff} KB${pct})`;
}

function statusIcon(pass) {
  return pass ? "✅" : "❌";
}

function sizeBar(kb, budgetKB) {
  const pct = Math.min(Math.round((kb / budgetKB) * 100), 100);
  const filled = Math.round(pct / 5);
  const empty = 20 - filled;
  return `${"█".repeat(filled)}${"░".repeat(empty)} ${pct}%`;
}

// ── Build comment ────────────────────────────────────────────────────────────

const lines = [];
const { summary } = current;

// Header
lines.push("## 📦 Bundle Size Report\n");

// Overall status
if (summary.overallPass) {
  lines.push(`> ✅ **All ${summary.totalRoutes} routes are within budget**\n`);
} else {
  lines.push(
    `> ❌ **${summary.failed} of ${summary.totalRoutes} routes exceeded their budget**\n`
  );
}

// Shared bundle
const baseShared = base?.sharedBundleKB;
lines.push(
  `**Shared bundle:** ${current.sharedBundleKB} KB${delta(current.sharedBundleKB, baseShared)} (${current.sharedBundleFiles} chunks)\n`
);

// Route table
lines.push("### Per-Route Breakdown\n");
lines.push("| Status | Route | Page KB | Total KB | Budget KB | Δ vs Base | Utilization |");
lines.push("|--------|-------|--------:|---------:|----------:|----------:|-------------|");

for (const route of current.routes) {
  const baseRoute = base?.routes?.find((r) => r.route === route.route);
  const baseTotalKB = baseRoute?.totalKB;
  const deltaStr = baseTotalKB != null ? delta(route.totalKB, baseTotalKB).trim() : "—";
  const bar = sizeBar(route.totalKB, route.scriptBudgetKB);

  lines.push(
    `| ${statusIcon(route.pass)} | \`${route.route}\` | ${route.pageKB} | ${route.totalKB} | ${route.scriptBudgetKB} | ${deltaStr} | ${bar} |`
  );
}

// Failed routes detail
if (summary.failed > 0) {
  lines.push("\n### ❌ Budget Violations\n");
  for (const route of current.routes.filter((r) => !r.pass)) {
    lines.push(
      `- **\`${route.route}\`** — ${route.totalKB} KB exceeds ${route.scriptBudgetKB} KB budget by **${route.overBudgetKB} KB**`
    );
  }
  lines.push(
    "\n> **💡 Tip:** Use `npm run analyze` locally to inspect the bundle treemap and identify large dependencies."
  );
}

// Size trends (if base exists)
if (base) {
  const totalCurrent = current.routes.reduce((s, r) => s + r.totalKB, 0);
  const totalBase = base.routes.reduce((s, r) => s + r.totalKB, 0);
  const totalDelta = totalCurrent - totalBase;
  const direction = totalDelta > 0 ? "📈" : totalDelta < 0 ? "📉" : "➡️";

  lines.push("\n### Size Trend\n");
  lines.push(
    `${direction} Aggregate route size: **${totalCurrent} KB** (was ${totalBase} KB, ${totalDelta > 0 ? "+" : ""}${totalDelta} KB)`
  );
}

// Footer
lines.push(
  "\n---\n<sub>Generated by bundle-size-monitor · budget config in <code>frontend/budget.json</code></sub>"
);

// ── Write output ─────────────────────────────────────────────────────────────

const comment = lines.join("\n");

try {
  await mkdir(analyzeDir, { recursive: true });
} catch {
  // already exists
}

await writeFile(outputPath, comment);
console.log(`✅ Bundle size comment written to .next/analyze/bundle-size-comment.md`);
console.log(`\n${comment}`);
